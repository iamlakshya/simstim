// This is a holder-only launch barrier after actual Store. commandProcess and
// the real owned Store runner still enforce1000. No holder or provider is run.
func storeCallerHolderBarrier(t *testing.T) error {
	t.Helper()
	barrier := errors.New("owned holder launch barrier after Store")
	old := plainHolderSpawnerForTests
	plainHolderSpawnerForTests = func() (*syscall.SysProcAttr, error) { return nil, barrier }
	t.Cleanup(func() { plainHolderSpawnerForTests = old })
	return barrier
}

const storeCallerReportScript = `import json, os, sys
value = sys.stdin.read()
if os.path.exists(sys.argv[1]):
    sys.exit(31)
with open(sys.argv[1], "w") as output:
    json.dump({"input": value, "uid": os.geteuid(), "gid": os.getegid(), "env": os.environ.get("STORE_KEY"), "exposed": os.environ.get("EXPOSED_KEY"), "home": os.environ.get("HOME"), "proxy": os.environ.get("HTTP_PROXY"), "ca": os.environ.get("SSL_CERT_FILE"), "metadata": {key: os.environ.get(key) for key in [sys.argv[2], sys.argv[3], "TERM", "COLORTERM", "TERM_PROGRAM", "TERM_PROGRAM_VERSION"]}}, output)
`

// Direct source witnesses bind the exact fields generated by host walled_env,
// members and sessionVars. They do not claim to call that host construction.
func directCallerIdentityEnv(base []string, member bool) []string {
	result := append([]string(nil), base...)
	id, hook, term, color, program, version := "store234", host.GuestHookSocket(), "xterm-256color", "truecolor", "primary-terminal", "1"
	if member {
		id, hook, term, color, program, version = "child234", host.GuestRunDir()+"/hook-child234.sock", "screen-256color", "24bit", "member-terminal", "2"
	}
	return append(result, brand.Env("SESSION")+"="+id, brand.Env("HOOK_SOCK")+"="+hook, "TERM="+term, "COLORTERM="+color, "TERM_PROGRAM="+program, "TERM_PROGRAM_VERSION="+version)
}

// prepareStoreCaller follows the actual production sub-operations. It runs
// the existing owned Store command; only the eventual holder is barred.
func prepareStoreCaller(t *testing.T, g *Init, args *proto.CtlStartArgs, primary bool) error {
	t.Helper()
	if g.lifetime == nil {
		ctx, cancel := context.WithCancel(context.Background())
		g.lifetime, g.cancelLifetime = ctx, cancel
		t.Cleanup(cancel)
	}
	delete(g.memberStarts, args.Session)
	args.PreparedClaim = ""
	args.RunToken = "current/" + args.Session
	target := proto.CtlSpawn
	if primary {
		target = proto.CtlStart
	}
	raw, err := json.Marshal(proto.CtlMemberPrepareArgs{Version: 1, Target: target, Start: *args})
	if err != nil {
		return err
	}
	result, err := g.prepareMember(raw)
	if err != nil {
		return err
	}
	args.PreparedClaim = result.Claim
	raw, err = json.Marshal(proto.CtlMemberPrepareArgs{Version: 1, Target: target, Start: *args})
	if err != nil {
		return err
	}
	return g.storePreparedMember(raw)
}

func TestOwnedStoreActualFreshWakeAndSpawnCallBeforeHolder(t *testing.T) {
	for _, restore := range []bool{true, false} {
		t.Run(map[bool]string{true: "fresh-or-wake", false: "member"}[restore], func(t *testing.T) {
			root, base := ownedStoreDirectories(t)
			report := filepath.Join(root, "work", "caller-report.json")
			kind := storeAgentFixture(t, []agents.SecretBinding{{Env: "STORE_KEY", Store: []string{"/usr/bin/python3", "-c", storeCallerReportScript, report, brand.Env("SESSION"), brand.Env("HOOK_SOCK")}}})
			barrier := storeCallerHolderBarrier(t)
			// The fixture's private root, home, work and all state/XDG paths are
			// owned1000 and traversable. The init's path mapping stays owned.
			g := &Init{root: root, primary: "store234", members: map[string]*holderProc{"parent234": {id: "parent234", done: make(chan struct{})}}, memberStarts: map[string]bool{"store234": true}, sessionPrepared: !restore}
			args := proto.CtlStartArgs{Session: "store234", Agent: kind, Argv: []string{"/usr/bin/true"}, Env: directCallerIdentityEnv(base, false), Cwd: filepath.Join(root, "work"), Secrets: map[string]string{"STORE_KEY": "public-sentinel-no-newline", "EXPOSED_KEY": "real-exposed-must-not-enter-Store"}, SecretModes: map[string]api.SecretMode{"STORE_KEY": api.SecretModeBound, "EXPOSED_KEY": api.SecretModeExposed}}
			if err := prepareStoreCaller(t, g, &args, restore); err != nil {
				t.Fatal(err)
			}
			_, err := g.startMember(args, restore)
			if !errors.Is(err, barrier) {
				t.Fatalf("actual start did not reach expected post-Store holder barrier: %v", err)
			}
			data, err := os.ReadFile(report)
			if err != nil {
				t.Fatal("actual common start path did not run Store")
			}
			var got struct {
				Input, Home, Proxy, CA string
				Env                    *string
				Exposed                *string
				UID, GID               int
				Metadata               map[string]*string
			}
			if err := json.Unmarshal(data, &got); err != nil {
				t.Fatal(err)
			}
			if got.Input != "public-sentinel-no-newline" || got.Env != nil || got.Exposed != nil || got.UID != AgentUID || got.GID != AgentGID || got.Home != envValue(base, "HOME") || got.Proxy != envValue(base, "HTTP_PROXY") || got.CA != envValue(base, "SSL_CERT_FILE") {
				t.Fatal("actual Store caller lost projection, fixed identity or materialised base environment")
			}
			if len(got.Metadata) != 6 {
				t.Fatal("Store metadata probe did not observe every excluded name")
			}
			for _, value := range got.Metadata {
				if value != nil {
					t.Fatal("per-member/terminal metadata reached actual Store process")
				}
			}
			manifestBytes, manifestErr := os.ReadFile(FilesFor(root, args.Session).Manifest)
			var manifest struct{ Env []string }
			if manifestErr == nil {
				manifestErr = json.Unmarshal(manifestBytes, &manifest)
			}
			if manifestErr != nil || envValue(manifest.Env, brand.Env("SESSION")) != "store234" || envValue(manifest.Env, brand.Env("HOOK_SOCK")) != g.mapValue(host.GuestHookSocket()) || envValue(manifest.Env, "TERM") != "xterm-256color" {
				t.Fatal("Store-only projection changed the eventual agent environment")
			}
			if len(g.owned) != 0 || g.secretStores == nil {
				t.Fatal("actual Store caller returned before owned cleanup/claim publication")
			}
			// startMember's Store succeeded but holder launch deliberately did
			// not. Retaining the installed claim still forbids rewriting it.
			delete(g.memberStarts, args.Session)
			args.Session = "child234"
			args.Env = directCallerIdentityEnv(base, true)
			// The primary command may have ended while another member keeps
			// the guest boot alive. Its installed Store claim still applies.
			g.members[g.primary] = &holderProc{id: g.primary, agentEnded: true, done: make(chan struct{})}
			if err := prepareStoreCaller(t, g, &args, false); err != nil {
				t.Fatal(err)
			}
			_, err = g.spawn(args)
			if !errors.Is(err, barrier) {
				t.Fatalf("same-context spawn reran Store or failed before holder: %v", err)
			}
			after, err := os.ReadFile(report)
			if err != nil || string(after) != string(data) {
				t.Fatal("idempotent spawn rewrote stored login data")
			}
		})
	}
}

func TestOwnedStoreActualChangedSentinelRefusesBeforeRewritingLogin(t *testing.T) {
	root, base := ownedStoreDirectories(t)
	report := filepath.Join(root, "work", "caller-report.json")
	kind := storeAgentFixture(t, []agents.SecretBinding{{Env: "STORE_KEY", Store: []string{"/usr/bin/python3", "-c", storeCallerReportScript, report, brand.Env("SESSION"), brand.Env("HOOK_SOCK")}}})
	barrier := storeCallerHolderBarrier(t)
	g := &Init{root: root, primary: "parent234", sessionPrepared: true, members: map[string]*holderProc{"parent234": {id: "parent234", done: make(chan struct{})}}, memberStarts: map[string]bool{"store234": true}}
	args := proto.CtlStartArgs{Session: "store234", Agent: kind, Argv: []string{"/usr/bin/true"}, Env: directCallerIdentityEnv(base, false), Cwd: filepath.Join(root, "work"), Secrets: map[string]string{"STORE_KEY": "public-original"}, SecretModes: map[string]api.SecretMode{"STORE_KEY": api.SecretModeBound}}
	if err := prepareStoreCaller(t, g, &args, false); err != nil {
		t.Fatal(err)
	}
	if _, err := g.startMember(args, false); !errors.Is(err, barrier) {
		t.Fatal("original actual Store did not reach holder barrier")
	}
	before, err := os.ReadFile(report)
	if err != nil {
		t.Fatal(err)
	}
	delete(g.memberStarts, args.Session)
	args.Session = "child234"
	args.Secrets = map[string]string{"STORE_KEY": "public-changed"}
	err = prepareStoreCaller(t, g, &args, false)
	requireSecretStoreError(t, err, "public-original", "public-changed")
	after, readErr := os.ReadFile(report)
	if readErr != nil || string(after) != string(before) || strings.Contains(string(after), "public-changed") {
		t.Fatal("refused member Store changed an installed login")
	}
	if len(g.owned) != 0 {
		t.Fatal("refused Store created an owned child")
	}
}

func TestOwnedStoreClaimMatchesActualCommandEnvironmentAndLeavesUserCommandAlone(t *testing.T) {
	root, base := ownedStoreDirectories(t)
	kind := storeAgentFixture(t, []agents.SecretBinding{{Env: "STORE_KEY", Store: []string{"/usr/bin/python3", "-c", "pass"}}})
	full := directCallerIdentityEnv(base, true)
	plans, env, err := prepareSecretStores("store234", kind, filepath.Join(root, "work"), full, map[string]api.Secret{"STORE_KEY": "public"})
	if err != nil || len(plans) != 1 {
		t.Fatal("selected internal Store did not prepare")
	}
	g := &Init{root: root}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	run := newOwnedCommand(ctx, proto.CtlExecArgs{ID: "store234", Argv: plans[0].argv, Cwd: filepath.Join(root, "work")}, env)
	defer run.cancel()
	cmd, _, err := g.agentCommand(run, io.Discard, io.Discard)
	if err != nil {
		t.Fatal(err)
	}
	claim := g.secretStoreInvocation(plans[0], filepath.Join(root, "work"), env)
	if !reflect.DeepEqual(claim.env, cmd.Env) || claim.cwd != cmd.Dir || !reflect.DeepEqual(claim.argv, cmd.Args) {
		t.Fatal("installation claim differs from actual owned command construction")
	}
	user := newOwnedCommand(ctx, proto.CtlExecArgs{ID: "store234", Argv: []string{"/usr/bin/python3", "-c", "pass"}, Cwd: filepath.Join(root, "work")}, full)
	defer user.cancel()
	userCmd, _, err := g.agentCommand(user, io.Discard, io.Discard)
	if err != nil {
		t.Fatal(err)
	}
	if envValue(userCmd.Env, brand.Env("SESSION")) != "child234" || envValue(userCmd.Env, "TERM") != "screen-256color" || envValue(userCmd.Env, brand.Env("HOOK_SOCK")) != g.mapValue(host.GuestRunDir()+"/hook-child234.sock") {
		t.Fatal("internal Store projection changed ordinary owned user-command metadata")
	}
}

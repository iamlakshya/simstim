// TrustNotice is printed by ssh-config (spec 17.7) so users understand the
// trust boundary of remote editor extensions.
const TrustNotice = "Note: VS Code and Cursor run an extension host whose remote side can run commands on your laptop by design.\n" +
	"For a repository you do not trust, use plain ssh, scp or sftp, or your editor's restricted mode."

// ErrOldOpenSSH is returned when the local ssh binary accepts shell characters
// in a hostname (CVE-2023-51385, fixed in OpenSSH 9.6).
var ErrOldOpenSSH = errors.New("this ssh passes shell characters in host names to ProxyCommand")

// CheckOpenSSH runs `ssh -G` on a hostname containing `$` (CVE-2023-51385).
// OpenSSH 9.6+ and patched backports reject it with a non-zero exit code.
func CheckOpenSSH(ctx context.Context, sshBin string) error {
	if sshBin == "" {
		sshBin = "ssh"
	}
	cctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	probe := "probe$x.check." + brand.Name
	cmd := exec.CommandContext(cctx, sshBin, "-G", "-F", os.DevNull, "--", probe)
	err := cmd.Run()
	if err == nil {
		return ErrOldOpenSSH
	}
	var ee *exec.ExitError
	if errors.As(err, &ee) {
		return nil
	}
	return fmt.Errorf("run %s to check CVE-2023-51385: %w", sshBin, err)
}

// ConfigPaths returns the paths under homeDir that ssh-config manages.
func ConfigPaths(homeDir string) (dir, cfgPath, knownHostsPath, userCfgPath string) {
	sshDir := filepath.Join(homeDir, ".ssh")
	dir = filepath.Join(sshDir, brand.Name)
	cfgPath = filepath.Join(dir, "config")
	knownHostsPath = filepath.Join(dir, "known_hosts")
	userCfgPath = filepath.Join(sshDir, "config")
	return dir, cfgPath, knownHostsPath, userCfgPath
}

// IncludeLine is the line added to the top of ~/.ssh/config.
func IncludeLine() string {
	return "Include ~/.ssh/" + brand.Name + "/config"
}

// ConfigBlock builds the SSH config block for *.<brand.Name> (spec 17.7).
// proxyCmd is the binary invocation (for example brand.Name or an explicit
// executable path when the binary is not on PATH).
func ConfigBlock(proxyCmd string) string {
	if proxyCmd == "" {
		proxyCmd = brand.Name
	}
	return fmt.Sprintf(`# Generated by %[1]s ssh-config. Run "%[1]s ssh-config --remove" to undo.
Host *.%[1]s
  ProxyCommand %[2]s ssh-proxy %%n
  User agent
  IdentityAgent none
  IdentityFile /dev/null
  IdentitiesOnly yes
  ForwardAgent no
  ForwardX11 no
  PermitLocalCommand no
  ControlMaster no
  StrictHostKeyChecking yes
  UserKnownHostsFile ~/.ssh/%[1]s/known_hosts
`, brand.Name, proxyCmd)
}

// WriteFiles writes ~/.ssh/<name>/config and ~/.ssh/<name>/known_hosts using
// signer's public key.
func WriteFiles(homeDir string, signer ssh.Signer, proxyCmd string) (cfgPath, khPath string, err error) {
	dir, cfgPath, khPath, _ := ConfigPaths(homeDir)
	sshDir := filepath.Dir(dir)
	if err := os.MkdirAll(sshDir, 0o700); err != nil {
		return "", "", fmt.Errorf("create %s: %w", sshDir, err)
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", "", fmt.Errorf("create %s: %w", dir, err)
	}
	if err := writeAtomic(cfgPath, []byte(ConfigBlock(proxyCmd))); err != nil {
		return "", "", err
	}
	if err := writeAtomic(khPath, []byte(KnownHostsLine(signer))); err != nil {
		return "", "", err
	}
	return cfgPath, khPath, nil
}

// EnsureInclude inserts the Include line at the top of ~/.ssh/config if it is
// not already present. It returns true when the file changed.
func EnsureInclude(homeDir string) (bool, error) {
	_, _, _, userCfg := ConfigPaths(homeDir)
	line := IncludeLine()
	existing, err := os.ReadFile(userCfg)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, fmt.Errorf("read %s: %w", userCfg, err)
	}
	for _, l := range strings.Split(string(existing), "\n") {
		if strings.TrimSpace(l) == line {
			return false, nil
		}
	}
	if err := os.MkdirAll(filepath.Dir(userCfg), 0o700); err != nil {
		return false, fmt.Errorf("create %s: %w", filepath.Dir(userCfg), err)
	}
	var updated string
	if len(existing) == 0 {
		updated = line + "\n"
	} else {
		updated = line + "\n\n" + string(existing)
	}
	if err := writeAtomic(userCfg, []byte(updated)); err != nil {
		return false, err
	}
	return true, nil
}

// Remove deletes ~/.ssh/<name>/ and removes the Include line from ~/.ssh/config.
func Remove(homeDir string) (removedInclude, removedDir bool, err error) {
	dir, _, _, userCfg := ConfigPaths(homeDir)
	if _, statErr := os.Stat(dir); statErr == nil {
		if err := os.RemoveAll(dir); err != nil {
			return false, false, fmt.Errorf("remove %s: %w", dir, err)
		}
		removedDir = true
	}
	existing, rerr := os.ReadFile(userCfg)
	if errors.Is(rerr, os.ErrNotExist) {
		return false, removedDir, nil
	}
	if rerr != nil {
		return false, removedDir, fmt.Errorf("read %s: %w", userCfg, rerr)
	}
	line := IncludeLine()
	lines := strings.Split(string(existing), "\n")
	var kept []string
	skipBlank := false
	for _, l := range lines {
		if strings.TrimSpace(l) == line {
			removedInclude = true
			skipBlank = true
			continue
		}
		if skipBlank && strings.TrimSpace(l) == "" {
			skipBlank = false
			continue
		}
		skipBlank = false
		kept = append(kept, l)
	}
	if removedInclude {
		if err := writeAtomic(userCfg, []byte(strings.Join(kept, "\n"))); err != nil {
			return false, removedDir, err
		}
	}
	return removedInclude, removedDir, nil
}

func writeAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	tmpName := tmp.Name()
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
		return fmt.Errorf("chmod %s: %w", path, err)
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		_ = os.Remove(tmpName)
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("close %s: %w", path, err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		_ = os.Remove(tmpName)
		return fmt.Errorf("rename %s: %w", path, err)
	}
	return nil
}

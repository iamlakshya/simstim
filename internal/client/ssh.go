// SSH runs the system OpenSSH client for one host. It never edits ~/.ssh/config:
// it passes a generated config that includes the user's own.
type SSH struct {
	Host Host
	// Interactive allows prompts (passwords, host keys, FIDO touches).
	Interactive bool
}

func home() string { h, _ := os.UserHomeDir(); return h }

// wrapperPath is the generated SSH config for one host.
func wrapperPath(h Host) string {
	return filepath.Join(ConfigDir(), "ssh", "config-"+h.Name)
}

// writeWrapper writes the generated SSH config for h. Order matters, because
// ssh uses the first value it finds: the client's hardening first, then the
// host's own config, then the user's, then the system's, then our defaults.
func writeWrapper(h Host) (string, error) {
	hostConfig := ""
	if h.SSHConfig != "" {
		hostConfig = expand(h.SSHConfig)
		if _, err := os.Stat(hostConfig); err != nil {
			return "", &UserError{Msg: fmt.Sprintf("the SSH config %s for host %s is missing", hostConfig, h.Name), Hint: brand.Name + " host edit " + h.Name}
		}
	}
	return writeConfig(wrapperPath(h), fmt.Sprintf("host %q", h.Name), hostConfig, true)
}

// DefaultSSHConfig writes the generated SSH config for a target that is not
// a saved host yet, such as the guided setup's first check, and returns its
// path. It is the user's own config, with the client's hardening first.
func DefaultSSHConfig() (string, error) {
	return writeConfig(filepath.Join(ConfigDir(), "ssh", "default"), "targets that are not hosts yet", "", false)
}

// writeConfig writes a generated SSH config to path, and leaves it alone
// when it has not changed. hostConfig, when set, is read before the user's
// config. defaults adds the client's own defaults at the end.
func writeConfig(path, what, hostConfig string, defaults bool) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by %s for %s. Do not edit; it is rewritten on each run.\n", brand.Name, what)
	// These lines come before every Include, so they win over every config
	// file. They reach a ProxyJump hop too: ssh starts the hop's own ssh with
	// this file's -F, but without the client's -o options (decision 0034).
	// ClearAllForwardings yes clears the forwards and the tunnel that a
	// config names for the hop. Forward's own command line says no, and
	// the command line comes first, so Forward keeps its -L options.
	block := slices.Concat(noForwarding, [][2]string{{"ClearAllForwardings", "yes"}})
	if sshKnowsFork() {
		// A hop or a host in the background would keep its forwards after
		// the client ends. A ControlPersist master still goes to the
		// background: ssh sets that for itself.
		block = append(block, [2]string{"ForkAfterAuthentication", "no"})
	}
	for _, o := range block {
		fmt.Fprintf(&b, "%s %s\n", o[0], o[1])
	}
	if hostConfig != "" {
		fmt.Fprintf(&b, "Include %q\n", hostConfig)
	}
	if p := filepath.Join(home(), ".ssh", "config"); exists(p) {
		fmt.Fprintf(&b, "Include %q\n", p)
	}
	if p := systemConfig(); exists(p) {
		fmt.Fprintf(&b, "Include %q\n", p)
	}
	if defaults {
		b.WriteString("Host *\n")
		b.WriteString("    ServerAliveInterval 10\n")
		b.WriteString("    ServerAliveCountMax 3\n")
		b.WriteString("    ConnectTimeout 15\n")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", fmt.Errorf("make %s: %w", filepath.Dir(path), err)
	}
	if old, err := os.ReadFile(path); err == nil && string(old) == b.String() {
		return path, nil
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o600); err != nil {
		return path, fmt.Errorf("write the SSH config %s: %w", path, err)
	}
	return path, nil
}

func exists(p string) bool { _, err := os.Stat(p); return err == nil }

// systemConfig is this computer's system SSH config. ssh reads it by
// itself, but not when -F names another file, so the generated configs
// include it. Tests replace it.
var systemConfig = func() string { return systemSSHConfig(runtime.GOOS, os.Getenv) }

// systemSSHConfig is the system SSH config on goos: %ProgramData%\ssh\ssh_config
// on Windows, and /etc/ssh/ssh_config elsewhere.
func systemSSHConfig(goos string, getenv func(string) string) string {
	if goos != "windows" {
		return "/etc/ssh/ssh_config"
	}
	dir := strings.TrimRight(getenv("PROGRAMDATA"), `\/`)
	if dir == "" {
		dir = `C:\ProgramData`
	}
	return dir + `\ssh\ssh_config`
}

// sshKnowsFork reports whether this computer's ssh knows the option
// ForkAfterAuthentication, which OpenSSH 8.7 added. Older versions stop on
// it, in a config file too. It asks ssh -G once for each run, which
// connects to nothing. Tests replace it.
var sshKnowsFork = sync.OnceValue(func() bool {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "ssh", "-G", "-F", os.DevNull, "-o", "ForkAfterAuthentication=no", "--", "probe.invalid")
	cmd.WaitDelay = sshWaitDelay
	return cmd.Run() == nil
})

func expand(p string) string {
	if rest, ok := strings.CutPrefix(p, "~/"); ok {
		return filepath.Join(home(), rest)
	}
	return p
}

// maxSocketPath is the longest socket path that works everywhere: macOS
// allows 104 bytes with the closing NUL, Linux 108.
const maxSocketPath = 103

// controlPrefix starts the name of each shared connection's socket. Older
// clients named their sockets without it, and their masters may still run,
// with an agent that the user's config forwarded. A master keeps what it
// forwarded for every session that it serves. So the client never uses one
// of those: a new name means a new master, which starts with forwarding off
// (decision 0034).
const controlPrefix = "nf-"

// controlDir is the folder for the shared connections' sockets. It is the
// cache folder when a socket path there fits in maxSocketPath (OpenSSH's %C
// is 40 characters, after controlPrefix), and otherwise a private folder of
// our own in /tmp. It is "" when neither can be used safely; the client
// then shares no connections, which is slower but works.
func controlDir() string {
	d := filepath.Join(CacheDir(), "cm")
	if len(d)+1+len(controlPrefix)+40 <= maxSocketPath {
		if os.MkdirAll(d, 0o700) != nil {
			return ""
		}
		return d
	}
	d = filepath.Join("/tmp", fmt.Sprintf("%s-%d", brand.Name, os.Getuid()))
	if err := os.Mkdir(d, 0o700); err != nil && !errors.Is(err, fs.ErrExist) {
		return ""
	}
	if !privateDir(d) {
		return ""
	}
	return d
}

// sshWaitDelay bounds the wait for ssh's output once ssh has ended or was
// killed. A child of ssh, such as a Match exec or a ProxyCommand, can hold
// stdout or stderr open, and without a bound the client would wait for it.
const sshWaitDelay = 2 * time.Second

// sharedDir is the folder of the shared connections' sockets, or "" when
// the client shares no connections: its OpenSSH cannot share them, or no
// private folder can be made.
func sharedDir() string {
	if !controlMaster {
		return ""
	}
	return controlDir()
}

// noForwarding is what a host must never get from this computer: its SSH
// agent, its X11 display and its Kerberos credentials. ssh also runs no
// LocalCommand here.
var noForwarding = [][2]string{
	{"ForwardAgent", "no"},
	{"ForwardX11", "no"},
	{"PermitLocalCommand", "no"},
	{"GSSAPIDelegateCredentials", "no"},
}

// NoForwarding returns the options that go on every ssh command line, from
// noForwarding. ssh keeps the first value that it finds for each of these
// options, and it reads the command line before any config file. So they
// win over a ForwardAgent yes in ~/.ssh/config (decision 0034).
func NoForwarding() []string {
	out := make([]string, 0, 2*len(noForwarding))
	for _, o := range noForwarding {
		out = append(out, "-o", o[0]+"="+o[1])
	}
	return out
}

// NoPortForwards returns the option that clears every port forward and the
// tunnel that a config file names. It goes on every ssh command that opens
// a session, but Forward's, as none of them needs a port forward. Forward
// does without it, because it would clear Forward's own -L options too.
func NoPortForwards() []string {
	return []string{"-o", "ClearAllForwardings=yes"}
}

// OwnConnection returns the options for a connection of its own, which
// neither uses nor starts a shared master: not the client's, and not one
// that the user's config names.
func OwnConnection() []string {
	return []string{"-o", "ControlMaster=no", "-o", "ControlPath=none"}
}

// baseArgs are the options of every ssh command for the host, on the
// host's shared connection.
func (s *SSH) baseArgs() ([]string, error) { return s.args(true) }

// args are the options of every ssh command for the host. With shared, the
// command uses the host's shared connection, and starts it when it is not
// running. Without, it has a connection of its own.
func (s *SSH) args(shared bool) ([]string, error) {
	cfg, err := writeWrapper(s.Host)
	if err != nil {
		return nil, err
	}
	args := append([]string{"-F", cfg}, NoForwarding()...)
	d := ""
	if shared {
		d = sharedDir()
	}
	switch {
	case d != "":
		args = append(args, "-o", "ControlMaster=auto", "-o", "ControlPath="+filepath.Join(d, controlPrefix+"%C"), "-o", "ControlPersist=600")
	case !shared || controlMaster:
		// A connection of its own, also when no private folder can be
		// made: the user's own ControlPath could name a master that an
		// older client started, with the agent forwarded.
		args = append(args, OwnConnection()...)
	}
	if !s.Interactive {
		args = append(args, "-o", "BatchMode=yes")
	}
	return args, nil
}

// RemoteHelper is the helper path for a version, in the remote shell's syntax.
func RemoteHelper(ver string) string {
	return fmt.Sprintf(`"$HOME/.local/share/%s/bin/%s/%s"`, brand.Name, ver, brand.HostBinary)
}

// Command builds an ssh command that runs remote (a shell command line) on
// the host. It carries the bridge (Start) and Run, so it clears the port
// forwards that a config file names.
func (s *SSH) Command(ctx context.Context, remote string, extra ...string) (*exec.Cmd, error) {
	args, err := s.baseArgs()
	if err != nil {
		return nil, err
	}
	args = append(args, NoPortForwards()...)
	args = append(args, extra...)
	args = append(args, "-e", "none", "--", s.Host.SSH, remote)
	cmd := exec.CommandContext(ctx, "ssh", args...)
	cmd.WaitDelay = sshWaitDelay
	return cmd, nil
}

// Run runs a remote command and returns its stdout. The error includes stderr.
func (s *SSH) Run(ctx context.Context, remote string, stdin io.Reader) ([]byte, error) {
	cmd, err := s.Command(ctx, remote, "-T")
	if err != nil {
		return nil, err
	}
	var out, errb bytes.Buffer
	cmd.Stdin = stdin
	cmd.Stdout = &out
	cmd.Stderr = &errb
	if s.Interactive {
		// The user sees what the host writes, as it comes, but cleaned.
		shown := &cleanWriter{w: os.Stderr}
		defer shown.Flush()
		cmd.Stderr = io.MultiWriter(&errb, shown)
	}
	if err := cmd.Run(); err != nil {
		return out.Bytes(), sshError(s.Host, err, errb.String())
	}
	return out.Bytes(), nil
}

// ExitMaster stops the ControlMaster for this host. Call it before reconnecting
// after a network change, because a master on a dead TCP connection hangs new sessions.
func (s *SSH) ExitMaster(ctx context.Context) {
	if s.Host.SSH == "" || sharedDir() == "" {
		return // no master of ours: never stop one that the user's config names
	}
	args, err := s.baseArgs()
	if err != nil {
		return
	}
	args = append(args, "-O", "exit", s.Host.SSH)
	// A master on a dead connection must not hang the reconnect for long.
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "ssh", args...)
	cmd.Stdout, cmd.Stderr = io.Discard, io.Discard
	cmd.WaitDelay = sshWaitDelay
	_ = cmd.Run()
}

// CheckMaster asks whether the master of the host's shared connection
// runs, with `ssh -O check`, and returns its process ID.
func (s *SSH) CheckMaster(ctx context.Context) (running bool, pid int) {
	if sharedDir() == "" {
		return false, 0 // no master of ours
	}
	args, err := s.baseArgs()
	if err != nil {
		return false, 0
	}
	args = append(args, "-O", "check", s.Host.SSH)
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "ssh", args...)
	cmd.WaitDelay = sshWaitDelay
	out, _ := cmd.CombinedOutput()
	return parseMaster(string(out))
}

// sshError turns ssh's exit status and stderr into a user error.
func sshError(h Host, err error, stderr string) error {
	msg := tailStderr(stderr)
	var ee *exec.ExitError
	if ok := asExit(err, &ee); ok && ee.ExitCode() == 255 {
		if msg == "" {
			msg = "ssh failed"
		}
		return &UserError{Msg: fmt.Sprintf("cannot reach %s: %s", h.Name, msg), Hint: fmt.Sprintf("ssh %s   (check that this works first)", h.SSH)}
	}
	if msg == "" {
		return err
	}
	return fmt.Errorf("%w: %s", err, msg)
}

func asExit(err error, target **exec.ExitError) bool {
	return errors.As(err, target)
}

// Shell builds an interactive ssh command that opens a login shell on the
// host, with no forwarding.
func (s *SSH) Shell(ctx context.Context) (*exec.Cmd, error) {
	args, err := s.baseArgs()
	if err != nil {
		return nil, err
	}
	args = append(args, NoPortForwards()...)
	args = append(args, "-t", "--", s.Host.SSH)
	return exec.CommandContext(ctx, "ssh", args...), nil
}

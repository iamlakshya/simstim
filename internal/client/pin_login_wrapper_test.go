func loginWrapperFixture(t *testing.T) (context.Context, Host, *loginWrapperScope) {
	t.Helper()
	fakeSSH(t)
	h := Host{Name: "setup-check-unit", SSH: "box.example"}
	ctx, abort, err := StagePinOwned(context.Background(), h.Name)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(abort)
	scope, err := beginLoginWrapperScope(ctx, h)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { scope.cleanup(ctx) })
	return ctx, h, scope
}

func loginWrapperBody(h Host) []byte {
	return fmt.Appendf(nil, "# Generated by %s for host %q. Do not edit; it is rewritten on each run.\nHost *\n", brand.Name, h.Name)
}

func TestLoginWrapperScopeOwnsOnlyItsPublishedDescriptor(t *testing.T) {
	ctx, h, scope := loginWrapperFixture(t)
	canonical := filepath.Join(ConfigDir(), "ssh", "config-"+HostFileKey(h.Name))
	user := []byte("Host user-config\n")
	if err := os.WriteFile(canonical, user, 0o600); err != nil {
		t.Fatal(err)
	}
	path, err := writeWrapper(h)
	if err != nil || path == canonical || path != scope.base {
		t.Fatalf("scoped wrapper path = %q, %v", path, err)
	}
	actual, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	scope.mu.Lock()
	owned, ok := scope.files[path]
	scope.mu.Unlock()
	if !ok || !os.SameFile(owned.info, actual) {
		t.Fatal("published descriptor identity was not captured")
	}
	scope.cleanup(ctx)
	if _, err := os.Stat(path); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("owned temporary wrapper remains: %v", err)
	}
	if got, err := os.ReadFile(canonical); err != nil || string(got) != string(user) {
		t.Fatalf("scoped cleanup changed a pre-existing canonical config: %v", err)
	}
}

func TestLoginWrapperScopeTracksEveryCurrentVariant(t *testing.T) {
	ctx, h, scope := loginWrapperFixture(t)
	paths := hostWrapperPaths(h)
	for _, path := range paths {
		hooks, err := loginWrapperWriteHooks(path, fmt.Sprintf("host %q", h.Name))
		if err != nil {
			t.Fatal(err)
		}
		if err := writeAtomicFileWithHooks(path, ".scoped-*", loginWrapperBody(h), hooks); err != nil {
			t.Fatal(err)
		}
	}
	scope.mu.Lock()
	count := len(scope.files)
	scope.mu.Unlock()
	if count != len(paths) {
		t.Fatalf("captured %d of %d current variants", count, len(paths))
	}
	scope.cleanup(ctx)
	for _, path := range paths {
		if _, err := os.Stat(path); !errors.Is(err, os.ErrNotExist) {
			t.Fatalf("owned current variant remains: %v", err)
		}
	}
}

func TestLoginWrapperScopeNeverAdoptsAPreExistingFile(t *testing.T) {
	for _, generated := range []bool{false, true} {
		t.Run(map[bool]string{false: "user", true: "unchanged generated"}[generated], func(t *testing.T) {
			ctx, h, scope := loginWrapperFixture(t)
			body := []byte("Host user-config\n")
			if generated {
				body = loginWrapperBody(h)
			}
			if err := os.WriteFile(scope.base, body, 0o600); err != nil {
				t.Fatal(err)
			}
			var user *UserError
			if _, err := writeWrapper(h); !errors.As(err, &user) || user.Code != "ssh_config_changed" {
				t.Fatalf("pre-existing wrapper was accepted: %v", err)
			}
			scope.cleanup(ctx)
			if got, err := os.ReadFile(scope.base); err != nil || string(got) != string(body) {
				t.Fatalf("cleanup adopted a pre-existing file: %v", err)
			}
		})
	}
}


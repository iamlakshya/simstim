// wrapperHeader identifies an exact-host generated config.
var wrapperHeader = "# Generated by " + brand.Name + " for host "

// oldWrapperPath is the generated config path used before per-host file
// keys. It is empty when name cannot safely name a host.
func oldWrapperPath(name string) string {
	if !ValidHostName(name) {
		return ""
	}
	return filepath.Join(ConfigDir(), "ssh", "config-"+name)
}

func generatedFor(path string) (name string, ok bool) {
	f, err := os.Open(path)
	if err != nil {
		return "", false
	}
	defer f.Close()
	return generatedConfigOwner(f)
}

// generatedConfigOwner checks the header from the same descriptor as its inode.
func generatedConfigOwner(r io.Reader) (name string, ok bool) {
	line, _ := bufio.NewReader(io.LimitReader(r, 512)).ReadString('\n')
	rest, ok := strings.CutPrefix(line, "# Generated by "+brand.Name+" for host ")
	if !ok {
		return "", false
	}
	quoted, _, ok := strings.Cut(rest, ". Do not edit")
	if !ok {
		return "", false
	}
	name, err := strconv.Unquote(quoted)
	return name, err == nil
}

// hostWrapperPaths lists every current wrapper variant for a host. A
// downstream environment policy extends this one accessor with its paths.
func hostWrapperPaths(h Host) []string { return []string{wrapperPath(h)} }

// removeHostWrappers runs under the caller's pin and hosts-file locks.
// remaining is the exact saved list after the proposed forget. It removes
// only unchanged owned configs that no remaining host references.
func removeHostWrappers(ctx context.Context, name string, remaining []Host) error {
	remove, err := prepareHostWrapperRemoval(ctx, name, remaining)
	if err != nil {
		return err
	}
	return remove()
}

// prepareHostWrapperRemoval captures provenance before a save's final
// cancellation hook. Its returned cleanup takes no locks and rechecks every
// captured inode against the exact post-change saved snapshot.
func prepareHostWrapperRemoval(ctx context.Context, name string, remaining []Host) (func() error, error) {
	paths := hostWrapperPaths(Host{Name: name})
	twin := slices.ContainsFunc(remaining, func(h Host) bool { return strings.EqualFold(h.Name, name) })
	if !twin {
		if old := oldWrapperPath(name); old != "" {
			paths = append(paths, old)
		}
	}
	var candidates []ownedSSHConfig
	for _, path := range paths {
		if path == "" {
			continue
		}
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		if info, err := os.Lstat(path); err == nil && info.IsDir() {
			return nil, fmt.Errorf("remove the generated SSH config: %s is a folder", path)
		}
		candidate, ok := snapshotGeneratedSSHConfig(path)
		if ok && candidate.owner == name {
			candidates = append(candidates, candidate)
		}
	}
	return func() error {
		if err := ctx.Err(); err != nil {
			return err
		}
		for _, candidate := range candidates {
			if err := unlinkOwnedSSHConfig(ctx, candidate, remaining); err != nil {
				return err
			}
		}
		return ctx.Err()
	}, nil
}

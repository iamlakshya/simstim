func wrapperForgetFixture(t *testing.T) (Host, string, []byte) {
	t.Helper()
	ownLockFiles(t, time.Millisecond, time.Second)
	h := Host{Name: "box", SSH: "box"}
	if err := SaveHosts(context.Background(), []Host{h}); err != nil {
		t.Fatal(err)
	}
	path := wrapperPath(h)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	contents := fmt.Appendf(nil, "# Generated by %s for host %q. Do not edit; it is rewritten on each run.\nHost box\n", brand.Name, h.Name)
	if err := os.WriteFile(path, contents, 0o600); err != nil {
		t.Fatal(err)
	}
	return h, path, contents
}

func TestForgetKeepsAnotherSavedHostsWrapperReference(t *testing.T) {
	for _, alias := range []bool{false, true} {
		t.Run(map[bool]string{false: "exact", true: "alias"}[alias], func(t *testing.T) {
			if alias && runtime.GOOS == "windows" {
				t.Skip("creating a symbolic link needs privileges on Windows")
			}
			h, path, contents := wrapperForgetFixture(t)
			reference := path
			if alias {
				reference = filepath.Join(t.TempDir(), "included")
				if err := os.Symlink(path, reference); err != nil {
					t.Fatal(err)
				}
			}
			other := Host{Name: "other", SSH: "other", SSHConfig: reference}
			if err := SaveHosts(context.Background(), []Host{h, other}); err != nil {
				t.Fatal(err)
			}
			if err := UpdateHosts(context.Background(), HostChange{Kind: "host rm", Was: &h}); err != nil {
				t.Fatal(err)
			}
			got, err := os.ReadFile(path)
			if err != nil || string(got) != string(contents) {
				t.Fatalf("forget removed another saved host's include: %v", err)
			}
			if _, err := FindHost(h.Name); err == nil {
				t.Fatal("reference preservation prevented the host forget")
			}
		})
	}
}

func TestForgetKeepsAUserOrForeignCurrentWrapper(t *testing.T) {
	for _, foreign := range []bool{false, true} {
		t.Run(map[bool]string{false: "user", true: "foreign owner"}[foreign], func(t *testing.T) {
			h, path, _ := wrapperForgetFixture(t)
			contents := []byte("Host custom\n")
			if foreign {
				contents = fmt.Appendf(nil, "# Generated by %s for host %q. Do not edit; it is rewritten on each run.\n", brand.Name, "other")
			}
			if err := os.WriteFile(path, contents, 0o600); err != nil {
				t.Fatal(err)
			}
			if err := UpdateHosts(context.Background(), HostChange{Kind: "host rm", Was: &h}); err != nil {
				t.Fatal(err)
			}
			got, err := os.ReadFile(path)
			if err != nil || string(got) != string(contents) {
				t.Fatalf("forget changed an unowned current wrapper: %v", err)
			}
		})
	}
}

func TestForgetKeepsAWrapperReplacedAtTheFinalSaveHook(t *testing.T) {
	h, path, original := wrapperForgetFixture(t)
	replacement := append(append([]byte(nil), original...), []byte("# replacement inode\n")...)
	before := beforeHostsSave
	beforeHostsSave = func() {
		if err := writeAtomicFile(path, ".replacement-*", replacement); err != nil {
			t.Error(err)
		}
	}
	t.Cleanup(func() { beforeHostsSave = before })
	if err := UpdateHosts(context.Background(), HostChange{Kind: "host rm", Was: &h}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != string(replacement) {
		t.Fatalf("forget removed a replacement inode: %v", err)
	}
}

func TestForgetRemovesOnlyItsUnreferencedOwnedWrapper(t *testing.T) {
	h, path, _ := wrapperForgetFixture(t)
	if err := UpdateHosts(context.Background(), HostChange{Kind: "host rm", Was: &h}); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(path); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("unchanged owned wrapper remains: %v", err)
	}
}

func TestPreCleanupCancellationKeepsThePinAndWrapper(t *testing.T) {
	h, path, wrapper := wrapperForgetFixture(t)
	key := newKey(t, "ssh-ed25519")
	if err := writeKeys(pinPath(h.Name), h.Name, []hostKey{key}); err != nil {
		t.Fatal(err)
	}
	pin, err := os.ReadFile(pinPath(h.Name))
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	before := beforeHostsSave
	beforeHostsSave = cancel
	t.Cleanup(func() { beforeHostsSave = before })
	if err := UpdateHosts(ctx, HostChange{Kind: "host rm", Was: &h}); !errors.Is(err, context.Canceled) {
		t.Fatalf("pre-cleanup cancellation = %v", err)
	}
	for path, want := range map[string][]byte{path: wrapper, pinPath(h.Name): pin} {
		got, err := os.ReadFile(path)
		if err != nil || string(got) != string(want) {
			t.Fatalf("pre-cleanup cancellation changed %s: %v", filepath.Base(path), err)
		}
	}
	if _, err := FindHost(h.Name); err != nil {
		t.Fatalf("pre-cleanup cancellation forgot the host: %v", err)
	}
}

func TestForgetStillRefusesAFolderAtItsWrapperPath(t *testing.T) {
	h, path, _ := wrapperForgetFixture(t)
	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(path, 0o700); err != nil {
		t.Fatal(err)
	}
	if err := UpdateHosts(context.Background(), HostChange{Kind: "host rm", Was: &h}); err == nil {
		t.Fatal("forget ignored its failed wrapper cleanup")
	}
	if _, err := FindHost(h.Name); err != nil {
		t.Fatalf("failed wrapper cleanup lost the retryable saved host: %v", err)
	}
}

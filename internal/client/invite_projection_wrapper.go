package client

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/iamlakshya/simstim/internal/brand"
)

// writeJoinedProjectionWrapperV1 contains no ambient Include. Its caller has
// already checked the actual private joined native source/lease for this Host.
func writeJoinedProjectionWrapperV1(ctx context.Context, h Host) (string, error) {
	restrict, err := shouldRestrictSSHEnv(ctx, h)
	if err != nil {
		return "", err
	}
	path := wrapperEnvPath(h, restrict)
	var text strings.Builder
	fmt.Fprintf(&text, "# Generated by %s for host %q. Do not edit; joined projection.\n", brand.Name, h.Name)
	for _, option := range noForwarding {
		fmt.Fprintf(&text, "%s %s\n", option[0], option[1])
	}
	text.WriteString("ClearAllForwardings yes\nPermitLocalCommand no\n")
	fmt.Fprintf(&text, "Include %q\nHost *\n    ServerAliveInterval 10\n    ServerAliveCountMax 3\n    ConnectTimeout 15\n", h.SSHConfig)
	if restrict {
		text.WriteString("    SendEnv -*\n    SendEnv LANG LC_*\n")
	}
	if err = ctx.Err(); err != nil {
		return "", err
	}
	if err = os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", err
	}
	hooks, err := loginWrapperWriteHooks(path, fmt.Sprintf("host %q", h.Name))
	if err != nil {
		return "", err
	}
	if old, err := os.ReadFile(path); err == nil && string(old) == text.String() {
		return path, nil
	}
	if err = writeAtomicFileWithHooks(path, ".joined-wrapper-*", []byte(text.String()), hooks); err != nil {
		return "", err
	}
	return path, nil
}

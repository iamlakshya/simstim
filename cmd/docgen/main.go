// Command docgen writes the reference docs from the code: the CLI reference,
// the config, key map and agent tables, and, on request, man pages and shell
// completions. It is a development tool and is never shipped.
//
//	go run ./cmd/docgen                       # docs/reference
//	go run ./cmd/docgen -man build/man -completions build/completions
//	go run ./cmd/docgen -site site/src -site-url https://docs.example.org/dev/
//
// The last writes the docs site's content for a build served at that
// address. scripts/docs-site.sh runs it with the right address.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	out := flag.String("out", "docs/reference", "where to write the reference pages")
	man := flag.String("man", "", "also write man pages into this folder")
	comp := flag.String("completions", "", "also write shell completions into this folder")
	site := flag.String("site", "", "also write the docs site's pages and data into this folder (the site's src)")
	siteURL := flag.String("site-url", "", "with -site: the address that this build of the docs site is served at, with its base, for llms.txt")
	flag.Parse()
	err := run(*out, *man, *comp)
	if err == nil && *site != "" {
		err = sitePages("docs", *site, repoURL(), *siteURL)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

func run(out, man, comp string) error {
	pages := map[string][]byte{}
	if err := cliPages(pages); err != nil {
		return err
	}
	cfg, err := configPage(".")
	if err != nil {
		return err
	}
	pages["config.md"] = cfg
	pages["keymap.md"] = keymapPage()
	pages["agents.md"] = agentsPage()
	pages["exit-codes.md"] = exitCodesPage()
	pages["_index.md"] = indexPage()
	if err := writeAll(out, pages); err != nil {
		return err
	}
	if man != "" {
		if err := manPages(man); err != nil {
			return err
		}
	}
	if comp != "" {
		if err := completions(comp); err != nil {
			return err
		}
	}
	return nil
}

// writeAll replaces the folder's generated files with pages, so a removed
// command loses its page too. It writes only files whose bytes changed.
func writeAll(dir string, pages map[string][]byte) error {
	if err := os.MkdirAll(filepath.Join(dir, "cli"), 0o755); err != nil {
		return fmt.Errorf("make %s: %w", dir, err)
	}
	old, _ := filepath.Glob(filepath.Join(dir, "cli", "*.md"))
	for _, f := range old {
		rel, _ := filepath.Rel(dir, f)
		if _, keep := pages[rel]; !keep {
			if err := os.Remove(f); err != nil {
				return fmt.Errorf("remove %s: %w", f, err)
			}
		}
	}
	for name, b := range pages {
		p := filepath.Join(dir, name)
		if cur, err := os.ReadFile(p); err == nil && bytes.Equal(cur, b) {
			continue
		}
		if err := os.WriteFile(p, b, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", p, err)
		}
	}
	return nil
}

// header starts every generated page: front matter for the docs site, and a
// note that the page is generated.
func header(title, weight string) string {
	h := "---\ntitle: " + quote(title) + "\n"
	if weight != "" {
		h += "weight: " + weight + "\n"
	}
	return h + "---\n\n<!-- Generated by `just docs` from the code. Do not edit by hand. -->\n\n"
}

// repoURL is the repository's address on GitHub, from go.mod's module path.
func repoURL() string {
	b, err := os.ReadFile("go.mod")
	if err != nil {
		return ""
	}
	for _, l := range strings.Split(string(b), "\n") {
		if m, ok := strings.CutPrefix(l, "module "); ok {
			return "https://" + strings.TrimSpace(m)
		}
	}
	return ""
}

func quote(s string) string {
	b := []byte{'"'}
	for _, r := range s {
		if r == '"' || r == '\\' {
			b = append(b, '\\')
		}
		b = append(b, string(r)...)
	}
	return string(append(b, '"'))
}
